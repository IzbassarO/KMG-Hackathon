export type SectionKind = "text" | "video" | "quiz";
export type CourseCategory = "Обязательный" | "Рекомендуемый" | "Бонус";
export type CourseLevel = "Базовый" | "Средний" | "Продвинутый";

export interface QuizQuestion {
  id: string;
  question: string;
  options: string[];
  correct: number;
}

export interface CourseSection {
  id: string;
  title: string;
  kind: SectionKind;
  /** для text: абзацы (разделены \n\n) */
  body?: string;
  /** для video: ссылка из lib/media.ts */
  videoUrl?: string;
  duration?: string;
  /** для quiz */
  questions?: QuizQuestion[];
}

export interface CourseModule {
  id: string;
  title: string;
  sections: CourseSection[];
}

export interface Course {
  id: string;
  title: string;
  description: string;
  category: CourseCategory;
  level: CourseLevel;
  duration: string;
  tags: string[];
  modules: CourseModule[];
}

