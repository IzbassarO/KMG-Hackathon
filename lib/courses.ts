export function getCourse(id: string): Course | undefined {
  return COURSES.find((c) => c.id === id);
}

export function courseSections(course: Course): CourseSection[] {
  return course.modules.flatMap((m) => m.sections);
}

export function courseSectionCount(course: Course): number {
  return course.modules.reduce((n, m) => n + m.sections.length, 0);
}
